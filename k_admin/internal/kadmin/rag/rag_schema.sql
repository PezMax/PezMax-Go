-- RAG retrieval schema for PostgreSQL + pgvector.
--
-- This file is mounted after extensions.sql on fresh Docker volumes. Existing
-- databases are migrated by internal/kadmin/rag.EnsureSchema when
-- KADMIN_RAG_ENABLED=true. The initial retrieval index is fixed at 1024 dimensions;
-- changing embedding dimensions requires a new schema/index migration.

CREATE TABLE IF NOT EXISTS public.rag_index_version (
    index_version       integer PRIMARY KEY,
    embedding_model     varchar(128) NOT NULL DEFAULT '',
    embedding_dim       integer NOT NULL DEFAULT 1024,
    model_fingerprint   varchar(128) NOT NULL DEFAULT '',
    status              varchar(16) NOT NULL DEFAULT 'unconfigured',
    metadata            jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_index_version_dim_ck CHECK (embedding_dim = 1024),
    CONSTRAINT rag_index_version_status_ck CHECK (status IN ('unconfigured', 'building', 'ready', 'retired', 'failed'))
);

INSERT INTO public.rag_index_version (index_version, embedding_model, embedding_dim, status)
VALUES (1, '', 1024, 'unconfigured')
ON CONFLICT (index_version) DO NOTHING;

-- One source resource and content version. source_id refers to ptmj_file or
-- ptmj_ebook according to source_kind; those tables remain the business truth.
CREATE TABLE IF NOT EXISTS public.rag_document (
    document_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_kind       varchar(16) NOT NULL,
    source_id         bigint NOT NULL,
    source_version    bigint NOT NULL DEFAULT 1,
    content_sha256    char(64) NOT NULL,
    review_state      varchar(24) NOT NULL DEFAULT 'queued',
    index_state       varchar(24) NOT NULL DEFAULT 'pending',
    visibility        boolean NOT NULL DEFAULT false,
    display_title     varchar(255) NOT NULL DEFAULT '',
    normalized        jsonb NOT NULL DEFAULT '{}'::jsonb,
    extraction_meta   jsonb NOT NULL DEFAULT '{}'::jsonb,
    model_versions    jsonb NOT NULL DEFAULT '{}'::jsonb,
    last_error_code   varchar(64) NOT NULL DEFAULT '',
    last_error        text NOT NULL DEFAULT '',
    created_at        timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_document_source_kind_ck CHECK (source_kind IN ('file', 'ebook')),
    CONSTRAINT rag_document_source_id_ck CHECK (source_id > 0),
    CONSTRAINT rag_document_source_version_ck CHECK (source_version > 0),
    CONSTRAINT rag_document_sha256_ck CHECK (content_sha256 ~ '^[0-9a-fA-F]{64}$'),
    CONSTRAINT rag_document_review_state_ck CHECK (
        review_state IN ('queued', 'extracting', 'reviewing', 'indexing', 'approved_pending_apply', 'needs_human', 'approved', 'rejected', 'stale', 'hidden', 'failed')
    ),
    CONSTRAINT rag_document_index_state_ck CHECK (
        index_state IN ('pending', 'extracting', 'embedding', 'ready', 'failed', 'stale')
    ),
    CONSTRAINT rag_document_normalized_object_ck CHECK (jsonb_typeof(normalized) = 'object'),
    CONSTRAINT rag_document_extraction_object_ck CHECK (jsonb_typeof(extraction_meta) = 'object'),
    CONSTRAINT rag_document_models_object_ck CHECK (jsonb_typeof(model_versions) = 'object'),
    UNIQUE (source_kind, source_id, source_version)
);

CREATE INDEX IF NOT EXISTS idx_rag_document_visibility
    ON public.rag_document (visibility, review_state, index_state, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_rag_document_source
    ON public.rag_document (source_kind, source_id, source_version DESC);
CREATE INDEX IF NOT EXISTS idx_rag_document_sha256
    ON public.rag_document (content_sha256);
-- pg_trgm fuzzy index for title recall: tolerates typos, spacing differences
-- and inconsistently named uploads that exact/tsvector matching misses.
CREATE INDEX IF NOT EXISTS idx_rag_document_title_trgm
    ON public.rag_document USING gin (display_title gin_trgm_ops);

-- Durable DB queue. Workers claim queued jobs with FOR UPDATE SKIP LOCKED.
CREATE TABLE IF NOT EXISTS public.rag_job (
    job_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   bigint NOT NULL REFERENCES public.rag_document(document_id) ON DELETE CASCADE,
    job_type      varchar(32) NOT NULL,
    status        varchar(16) NOT NULL DEFAULT 'queued',
    priority      integer NOT NULL DEFAULT 100,
    attempts      integer NOT NULL DEFAULT 0,
    max_attempts  integer NOT NULL DEFAULT 4,
    run_after     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    locked_at     timestamp,
    locked_by     varchar(128) NOT NULL DEFAULT '',
    heartbeat_at  timestamp,
    error_code    varchar(64) NOT NULL DEFAULT '',
    last_error    text NOT NULL DEFAULT '',
    created_at    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_job_type_ck CHECK (job_type IN ('extract', 'review', 'embed', 'reindex')),
    CONSTRAINT rag_job_status_ck CHECK (status IN ('queued', 'running', 'done', 'failed', 'cancelled')),
    CONSTRAINT rag_job_priority_ck CHECK (priority >= 0),
    CONSTRAINT rag_job_attempts_ck CHECK (attempts >= 0 AND max_attempts > 0 AND attempts <= max_attempts)
);

CREATE INDEX IF NOT EXISTS idx_rag_job_claim
    ON public.rag_job (status, run_after, priority, job_id);
CREATE INDEX IF NOT EXISTS idx_rag_job_document
    ON public.rag_job (document_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uk_rag_job_active
    ON public.rag_job (document_id, job_type)
    WHERE status IN ('queued', 'running');

-- Question-level and document-summary chunks. The first production index uses
-- BGE-M3/Qwen-compatible 1024-dimensional vectors.
CREATE TABLE IF NOT EXISTS public.rag_chunk (
    chunk_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    bigint NOT NULL REFERENCES public.rag_document(document_id) ON DELETE CASCADE,
    index_version  integer NOT NULL DEFAULT 1 REFERENCES public.rag_index_version(index_version),
    chunk_type     varchar(24) NOT NULL,
    page_start     integer NOT NULL,
    page_end       integer NOT NULL,
    question_no    varchar(64) NOT NULL DEFAULT '',
    ordinal        integer NOT NULL DEFAULT 0,
    content        text NOT NULL,
    normalized     text NOT NULL,
    search_text    text NOT NULL DEFAULT '',
    metadata       jsonb NOT NULL DEFAULT '{}'::jsonb,
    embedding      vector(1024),
    visibility     boolean NOT NULL DEFAULT false,
    created_at     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_chunk_type_ck CHECK (chunk_type IN ('summary', 'stem', 'options', 'answer', 'explanation', 'passage')),
    CONSTRAINT rag_chunk_page_ck CHECK (page_start > 0 AND page_end >= page_start),
    CONSTRAINT rag_chunk_ordinal_ck CHECK (ordinal >= 0),
    CONSTRAINT rag_chunk_metadata_object_ck CHECK (jsonb_typeof(metadata) = 'object'),
    UNIQUE (document_id, index_version, page_start, page_end, question_no, chunk_type, ordinal)
);

CREATE INDEX IF NOT EXISTS idx_rag_chunk_document
    ON public.rag_chunk (document_id, index_version, visibility, page_start, ordinal);
CREATE INDEX IF NOT EXISTS idx_rag_chunk_visible_document
    ON public.rag_chunk (visibility, index_version, document_id, page_start);
CREATE INDEX IF NOT EXISTS idx_rag_chunk_lexical
    ON public.rag_chunk USING gin (to_tsvector('simple', search_text));
-- pg_trgm fuzzy index for the lexical fallback: CJK bigrams and typos that the
-- tsvector index above cannot match still return candidates via similarity().
CREATE INDEX IF NOT EXISTS idx_rag_chunk_trgm
    ON public.rag_chunk USING gin (search_text gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_rag_chunk_embedding
    ON public.rag_chunk USING hnsw (embedding vector_cosine_ops)
    WHERE visibility AND embedding IS NOT NULL;

-- Append-only model and human review evidence.
CREATE TABLE IF NOT EXISTS public.rag_review (
    review_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     bigint NOT NULL REFERENCES public.rag_document(document_id) ON DELETE CASCADE,
    decision        varchar(24) NOT NULL,
    confidence      numeric(6,5) NOT NULL DEFAULT 0,
    findings        jsonb NOT NULL DEFAULT '[]'::jsonb,
    normalized      jsonb NOT NULL DEFAULT '{}'::jsonb,
    model_name      varchar(128) NOT NULL DEFAULT '',
    prompt_version  varchar(64) NOT NULL DEFAULT '',
    reviewer_id     bigint,
    reason          text NOT NULL DEFAULT '',
    created_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_review_decision_ck CHECK (decision IN ('approve', 'reject', 'needs_human')),
    CONSTRAINT rag_review_confidence_ck CHECK (confidence BETWEEN 0 AND 1),
    CONSTRAINT rag_review_findings_array_ck CHECK (jsonb_typeof(findings) = 'array'),
    CONSTRAINT rag_review_normalized_object_ck CHECK (jsonb_typeof(normalized) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_rag_review_document
    ON public.rag_review (document_id, created_at DESC, review_id DESC);
CREATE INDEX IF NOT EXISTS idx_rag_review_decision
    ON public.rag_review (decision, created_at DESC);

-- Query telemetry. query_text is optional and should be cleared by retention
-- policy when privacy requirements prohibit storing the original query.
CREATE TABLE IF NOT EXISTS public.rag_query_log (
    query_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_hash      char(64) NOT NULL,
    query_text      text NOT NULL DEFAULT '',
    plan            jsonb NOT NULL DEFAULT '{}'::jsonb,
    result_count    integer NOT NULL DEFAULT 0,
    degraded        boolean NOT NULL DEFAULT false,
    latency_ms      integer NOT NULL DEFAULT 0,
    model_versions  jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT rag_query_hash_ck CHECK (query_hash ~ '^[0-9a-fA-F]{64}$'),
    CONSTRAINT rag_query_result_count_ck CHECK (result_count >= 0),
    CONSTRAINT rag_query_latency_ck CHECK (latency_ms >= 0),
    CONSTRAINT rag_query_plan_object_ck CHECK (jsonb_typeof(plan) = 'object'),
    CONSTRAINT rag_query_models_object_ck CHECK (jsonb_typeof(model_versions) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_rag_query_log_created
    ON public.rag_query_log (created_at DESC, query_id DESC);
CREATE INDEX IF NOT EXISTS idx_rag_query_log_hash
    ON public.rag_query_log (query_hash, created_at DESC);
